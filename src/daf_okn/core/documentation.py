"""Introspected API reference markdown for the real daf_okn modules.

:func:`build_api_reference_markdown` imports each module listed in
``_DOCUMENTED_MODULES`` and renders its public API (per the module's own
``__all__``): classes and functions with their live ``inspect`` signatures and
first docstring line. ``scripts/generate_api_docs.py`` persists the result to
``output/docs/api_reference.md`` — there is no hand-maintained template, so the
reference cannot drift from the code.
"""

from __future__ import annotations

import importlib
import inspect
from types import ModuleType
from typing import Any

# Documented in narrative order: graph core → analysis → presentation.
_DOCUMENTED_MODULES: tuple[str, ...] = (
    "daf_okn.core.graph",
    "daf_okn.core.registry",
    "daf_okn.core.invariants",
    "daf_okn.core.cognitive_adapter",
    "daf_okn.core.keyword_terms",
    "daf_okn.core.rdf",
    "daf_okn.core.rdf_submission",
    "daf_okn.core.join_report",
    "daf_okn.core.join_evidence",
    "daf_okn.analysis.cross_graph",
    "daf_okn.analysis.join_explanation",
    "daf_okn.core.contribute",
    "daf_okn.analysis.graph_metrics",
    "daf_okn.analysis.pipeline",
    "daf_okn.figures.network_figure",
    "daf_okn.dashboard.dashboard",
    "daf_okn.dashboard.dashboard_payload",
    "daf_okn.cli",
)

_HEADER = """# DAF-OKN API Reference

Generated by `scripts/generate_api_docs.py` via
`daf_okn.core.documentation.build_api_reference_markdown()`, which introspects
the live `daf_okn` modules with `inspect`. Signatures below are read from the
running code at generation time; the first docstring line of each public
callable is quoted verbatim.
"""


def _module_summary_line(module: ModuleType) -> str:
    """Return the module docstring's first line (empty string when absent)."""
    doc = inspect.getdoc(module)
    return doc.splitlines()[0] if doc else ""


def _documented_members(module: ModuleType) -> list[tuple[str, Any]]:
    """Return the module's own public classes/functions in ``__all__`` order.

    Members re-imported from other modules are skipped so each symbol is
    documented exactly once, under its defining module.
    """
    names = getattr(module, "__all__", None) or [
        name for name in dir(module) if not name.startswith("_")
    ]
    members: list[tuple[str, Any]] = []
    for name in names:
        obj = getattr(module, name, None)
        if obj is None or getattr(obj, "__module__", None) != module.__name__:
            continue
        if inspect.isfunction(obj) or inspect.isclass(obj):
            members.append((name, obj))
    return members


def _signature_line(obj: Any) -> str:
    """Render ``name(signature)``; callables without a readable signature fall
    back to ``name(...)`` instead of raising."""
    try:
        signature = str(inspect.signature(obj))
    except (TypeError, ValueError):  # pragma: no cover — defensive, builtins only
        signature = "(...)"
    return f"{obj.__name__}{signature}"


def _first_doc_line(obj: Any) -> str:
    """Return the first line of the object's docstring (empty string when absent)."""
    doc = inspect.getdoc(obj)
    return doc.splitlines()[0] if doc else ""


def _class_methods(cls: type) -> list[str]:
    """Render the public methods of *cls* as signature bullets."""
    methods: list[str] = []
    for name, member in inspect.getmembers(cls, predicate=callable):
        if name.startswith("_") or getattr(member, "__module__", None) != cls.__module__:
            continue
        methods.append(f"  - `{_signature_line(member)}` — {_first_doc_line(member)}")
    return methods


def _member_bullet(name: str, obj: Any) -> list[str]:
    """Render one documented member as markdown lines."""
    lines = [f"- `{_signature_line(obj)}`", f"  {_first_doc_line(obj)}"]
    if inspect.isclass(obj):
        methods = _class_methods(obj)
        if methods:
            lines.append("")
            lines.extend(methods)
    return lines


def _module_section(module_name: str) -> str:
    """Render one ``##`` section for *module_name* (imported live)."""
    module = importlib.import_module(module_name)
    lines = [f"## `{module_name}`", "", _module_summary_line(module), ""]
    members = _documented_members(module)
    if not members:
        lines.append("_No own public classes or functions (re-export module)._")
        lines.append("")
    for name, obj in members:
        lines.extend(_member_bullet(name, obj))
        lines.append("")
    return "\n".join(lines)


def build_api_reference_markdown(
    modules: tuple[str, ...] | None = None,
) -> str:
    """Return the introspected API reference markdown for *modules*.

    Args:
        modules: Module dotted paths to document; defaults to the pinned
            daf-okn module list (graph core, registry, invariants, cognitive
            adapter, contribute, graph metrics, pipeline, figures, dashboard).

    Returns:
        The complete markdown document.
    """
    documented = modules if modules is not None else _DOCUMENTED_MODULES
    parts = [_HEADER]
    for module_name in documented:
        parts.append(_module_section(module_name))
    return "\n".join(parts)


__all__ = ["_DOCUMENTED_MODULES", "build_api_reference_markdown"]
